"""RAG pipeline for the three VRSpecML profile tasks.

Task 1  Ontology → UML profile: stereotypes per metaclass.
Task 2  Ontology + guidelines → tagged values (types, multiplicities, units,
        bounds, example values) and enumerations.
Task 3  SOPs + ontology → OCL invariants written by Qwen.

Everything the profile contains is generated by Qwen from retrieved evidence; the code
only retrieves, prompts and stores (no validation, derivation or re-alignment).
"""
import logging
import re
import time
from concurrent.futures import ThreadPoolExecutor, as_completed
from typing import Any, Callable, Dict, List, Optional, Tuple

import config
from grounding import EvidencePack
from llm_client import LLMError, QwenClient
from metamodel import (METACLASSES, PRIMITIVE_TYPES, normalize_multiplicity, split_camel,
                       to_enum_literal, to_lower_camel, to_upper_camel)
from prompts import SYSTEM, analysis_prompt, associations_prompt, ocl_prompt, stereotype_prompt, tags_prompt
from schemas import (FACETS, ContextAnalysis, Enumeration, Invariant, Profile, Stereotype, TaggedValue,
                     analysis_schema, associations_schema, ocl_schema, stereotype_schema, tags_schema)

logger = logging.getLogger(__name__)
Progress = Optional[Callable[[str, float], None]]

def _strip_citations(text: str) -> str:
    """Remove '(Evidence: [R6])' / '[S2]' style id citations the model sometimes writes into prose."""
    text = re.sub(r"\(\s*(?:evidence|source|see)?\s*:?\s*(?:\[?[A-Z]\d+\]?[,;\s]*)+\)", "", text, flags=re.I)
    text = re.sub(r"\[[A-Z]\d+\](?:\s*[,;]\s*\[[A-Z]\d+\])*", "", text)
    text = re.sub(r"\s+([,.;])", r"\1", text)
    return re.sub(r"\s{2,}", " ", text).strip()


def now() -> str:
    return time.strftime("%Y-%m-%d %H:%M:%S")


def new_profile(domain, context: str) -> Profile:
    return Profile(domain_id=domain.id, domain_name=domain.name, package=domain.package,
                   context=context, created=now(), updated=now())


def rename_stereotype(profile: Profile, sid: str, new_name: str) -> Optional[str]:
    """Rename a stereotype and propagate to association types and OCL bodies."""
    st = profile.by_sid(sid)
    if st is None:
        return None
    new = to_upper_camel(new_name)
    if new == st.name:
        return new
    taken = {s.name for s in profile.stereotypes if s.sid != sid} | {e.name for e in profile.enumerations}
    base, n = new, 2
    while new in taken or new in METACLASSES or new in PRIMITIVE_TYPES:
        new, n = f"{base}{n}", n + 1
    old = st.name
    st.name = new
    word = re.compile(rf"\b{re.escape(old)}\b")
    for tags in profile.tagged_values.values():
        for t in tags:
            if t.type == old:
                t.type = new
            if t.example == old:
                t.example = new
    for inv in profile.invariants:
        inv.body = word.sub(new, inv.body)
        if inv.context_sid == sid:
            inv.context = new
    profile.updated = now()
    return new


def cleanup_enumerations(profile: Profile) -> None:
    used = {t.type for tags in profile.tagged_values.values() for t in tags}
    referenced = " ".join(i.body for i in profile.invariants)
    profile.enumerations = [e for e in profile.enumerations if e.name in used or f"{e.name}::" in referenced]


def remove_stereotype(profile: Profile, sid: str) -> bool:
    """Delete a stereotype together with everything that depends on it: its tagged values,
    association tags in other stereotypes that point at it, and invariants that use it."""
    st = profile.by_sid(sid)
    if st is None:
        return False
    word = re.compile(rf"\b{re.escape(st.name)}\b")
    profile.stereotypes = [s for s in profile.stereotypes if s.sid != sid]
    profile.tagged_values.pop(sid, None)
    for other, tags in profile.tagged_values.items():
        profile.tagged_values[other] = [t for t in tags if t.type != st.name]
    profile.invariants = [i for i in profile.invariants if i.context_sid != sid and not word.search(i.body)]
    cleanup_enumerations(profile)
    profile.updated = now()
    return True


def add_stereotype(profile: Profile, name: str, metaclass: str, description: str = "") -> Stereotype:
    """Append a user-defined stereotype (no tagged values yet). Raises ValueError for an unusable name."""
    new = to_upper_camel(name)
    if not new or new == "Unnamed":
        raise ValueError("Enter a stereotype name.")
    taken = {s.name.lower() for s in profile.stereotypes} | {e.name.lower() for e in profile.enumerations}
    if new.lower() in taken or new in METACLASSES or new in PRIMITIVE_TYPES:
        raise ValueError(f"The name «{new}» is already used.")
    n = max([int(s.sid[2:]) for s in profile.stereotypes if s.sid[2:].isdigit()] + [0]) + 1
    st = Stereotype(sid=f"ST{n:02d}", name=new, extends=metaclass, mapping="extension", description=description.strip())
    profile.stereotypes.append(st)
    profile.updated = now()
    return st


class Pipeline:
    def __init__(self, kb, domain, client: QwenClient, parallel: int = config.LLM_PARALLEL):
        self.kb = kb
        self.domain = domain
        self.client = client
        self.parallel = max(1, parallel)

    # ── shared helpers ───────────────────────────────────────────────────
    def _log(self, profile: Profile, task: str, message: str, **extra):
        profile.task_log.append({"time": now(), "task": task, "message": message, **extra})

    @staticmethod
    def _facet_values(analysis: Optional[ContextAnalysis], keys: List[str]) -> List[str]:
        if not analysis:
            return []
        vals: List[str] = []
        for k in keys:
            for v in getattr(analysis, k, []) or []:
                if v not in vals:
                    vals.append(v)
        return vals

    def _run_parallel(self, jobs: List[Tuple[str, Callable[[], Any]]], progress: Progress, label: str,
                      span: Tuple[float, float] = (0.0, 1.0)):
        """Run labelled jobs on the worker pool; report progress from the calling thread."""
        results, errors = {}, {}
        if not jobs:
            return results, errors
        lo, hi = span
        done = 0
        with ThreadPoolExecutor(max_workers=self.parallel) as pool:
            futures = {pool.submit(fn): key for key, fn in jobs}
            for fut in as_completed(futures):
                key = futures[fut]
                try:
                    results[key] = fut.result()
                except Exception as exc:  # one failed item must not sink the whole task
                    logger.exception("%s failed for %s", label, key)
                    errors[key] = str(exc)
                done += 1
                if progress:
                    progress(f"{label}: {done}/{len(jobs)} ({key})", lo + (hi - lo) * done / len(jobs))
        return results, errors

    # ── context analysis ─────────────────────────────────────────────────
    def analyze(self, context: str) -> ContextAnalysis:
        if not context.strip():
            return ContextAnalysis(summary=self.domain.description)
        data = self.client.chat_json(SYSTEM, analysis_prompt(self.domain.name, context), analysis_schema(),
                                     max_tokens=900, task="context analysis")
        clean: Dict[str, Any] = {"summary": str(data.get("summary", "")).strip()}
        for f in FACETS:
            seen: List[str] = []
            for v in data.get(f, []) or []:
                v = " ".join(str(v).split()).strip(" .;,")
                if v and v.lower() not in {s.lower() for s in seen}:
                    seen.append(v)
            clean[f] = seen[:8]
        return ContextAnalysis(**clean)

    # ── Task 1: stereotypes ──────────────────────────────────────────────
    def _task1_evidence(self, metaclass: str, analysis: ContextAnalysis, context: str) -> EvidencePack:
        focus = self.domain.metaclass_focus[metaclass]
        facets = self._facet_values(analysis, focus.facets)
        facet_text = " ".join(facets)
        summary = analysis.summary or context[:400]
        base = {"files": focus.ontologies, "exclude_sources": ["UO"]}
        queries = [(f"{focus.query} {facet_text}", 1.0, base)]
        for key in focus.ontologies:
            queries.append((f"{focus.query} {facet_text}", 0.5, {"files": [key], "exclude_sources": ["UO"]}))
        if summary:
            queries.append((summary, 0.6, base))
        for v in facets[:12]:
            queries.append((v, 0.35, base))
        pack = EvidencePack()
        for doc, _ in self.kb.search_many("class", queries, k=config.CLASS_CANDIDATES_PER_PROMPT):
            pack.add_class(doc)
        sop_queries = [(f"{focus.query} {facet_text}", 1.0, None), (summary, 0.8, None)]
        for doc, _ in self.kb.search_many("chunk", sop_queries, k=config.SOP_CHUNKS_PER_PROMPT):
            pack.add_chunk(doc)
        return pack

    def _task1_metaclass(self, metaclass: str, context: str, analysis: ContextAnalysis, n: int):
        pack = self._task1_evidence(metaclass, analysis, context)
        prompt = stereotype_prompt(self.domain, metaclass, context, analysis.model_dump(), pack.text("O"),
                                   pack.text("S"), n, [])
        schema = stereotype_schema(pack.ids("O"), pack.ids("S"), n, n + 2)
        raw = self.client.chat_json(SYSTEM, prompt, schema, max_tokens=320 * (n + 2) + 400,
                                    task=f"task1 {metaclass}")
        return raw, pack

    def _stereotype_from_raw(self, metaclass: str, item: Dict[str, Any], pack: EvidencePack) -> Stereotype:
        name = to_upper_camel(re.sub(r"(?i)stereotype$", "", str(item.get("name", "")).strip()))
        if name in METACLASSES or name in PRIMITIVE_TYPES:
            name = "Farm" + name
        onto = pack.resolve(item.get("ontology_refs", []))
        primary = pack.resolve([item.get("primary_ref", "none")])
        mapping = item.get("mapping", "extension")
        notes = []
        if primary:
            onto = primary + [r for r in onto if r.id != primary[0].id]
        if mapping == "ontology" and not primary:
            if onto:
                primary = onto[:1]
            else:
                mapping = "extension"
                notes.append("claimed ontology mapping without a candidate; recorded as extension")
        if mapping == "extension" and primary:
            mapping = "ontology"
        sop = pack.resolve(item.get("sop_refs", []))
        if mapping == "extension" and not (sop or onto):
            notes.append("extension without cited evidence (context-driven)")
        try:
            confidence = min(1.0, max(0.0, float(item.get("confidence", 0.5))))
        except (TypeError, ValueError):
            confidence = 0.5
        return Stereotype(
            sid="", name=name, extends=metaclass, mapping=mapping,
            description=str(item.get("description", "")).strip(),
            rationale=str(item.get("rationale", "")).strip(), confidence=confidence,
            primary=primary[0] if primary else None, ontology_refs=onto, sop_refs=sop, notes=notes,
        )

    def run_task1(self, profile: Profile, per_metaclass: int = config.STEREOTYPES_PER_METACLASS,
                  progress: Progress = None) -> Profile:
        if progress:
            progress("Analysing context", 0.02)
        profile.analysis = self.analyze(profile.context)
        profile.model = self.client.model
        jobs = [(m, (lambda m=m: self._task1_metaclass(m, profile.context, profile.analysis, per_metaclass)))
                for m in METACLASSES]
        results, errors = self._run_parallel(jobs, progress, "Stereotypes", (0.08, 0.9))
        if errors and not results:
            raise LLMError("; ".join(f"{k}: {v}" for k, v in errors.items()))

        candidates: List[Stereotype] = []
        for m in METACLASSES:
            if m not in results:
                continue
            raw, pack = results[m]
            for item in raw.get("stereotypes", []):
                st = self._stereotype_from_raw(m, item, pack)
                if st.name != "Unnamed":
                    candidates.append(st)

        # unique names only
        candidates.sort(key=lambda s: -s.confidence)
        chosen: List[Stereotype] = []
        names = set()
        for st in candidates:
            if st.name.lower() in names:
                continue
            names.add(st.name.lower())
            chosen.append(st)

        order = {m: i for i, m in enumerate(METACLASSES)}
        chosen.sort(key=lambda s: (order[s.extends], -s.confidence))
        for i, st in enumerate(chosen, start=1):
            st.sid = f"ST{i:02d}"

        if progress:
            progress("Scoring grounding", 0.93)
        for st in chosen:
            text = f"{split_camel(st.name)}. {st.description}"
            st.grounding = round(max(
                self.kb.similarity(text, "class", [r.id for r in st.ontology_refs]),
                self.kb.similarity(text, "chunk", [r.id for r in st.sop_refs]),
            ), 3)

        profile.stereotypes = chosen
        profile.tagged_values, profile.enumerations, profile.invariants = {}, [], []
        for m, err in errors.items():
            self._log(profile, "task1", f"«{m}» failed: {err}", level="error")
        self._log(profile, "task1", f"{len(chosen)} stereotypes", usage=self.client.usage_summary())
        profile.updated = now()
        return profile

    # ── shared context helpers for Tasks 2/3 ─────────────────────────────
    def _digest(self, profile: Profile, metaclass: Optional[str] = None) -> str:
        """Context summary + facets (instead of the raw text, which makes every element copy it)."""
        a = profile.analysis
        if not a:
            return profile.context[:600]
        keys = self.domain.metaclass_focus[metaclass].facets if metaclass else [f for f in FACETS if f != "constraints"]
        facets = "; ".join(f"{k.replace('_', ' ')}: {', '.join(getattr(a, k))}" for k in keys
                           if k != "constraints" and getattr(a, k))
        return f"{a.summary} {('(' + facets + ')') if facets else ''}".strip()

    def _route_constraints(self, profile: Profile) -> Dict[str, List[Tuple[int, str]]]:
        """Give each user-stated constraint only to its most relevant stereotypes (top 3 by similarity)."""
        from embedder import embed

        constraints = (profile.analysis.constraints if profile.analysis else [])[:8]
        kept = profile.kept()
        routed: Dict[str, List[Tuple[int, str]]] = {s.sid: [] for s in kept}
        if not constraints or not kept:
            return routed
        st_vecs = embed([f"{split_camel(s.name)}. {s.description}" for s in kept])
        c_vecs = embed(constraints)
        for ci, (c, cv) in enumerate(zip(constraints, c_vecs), start=1):
            sims = st_vecs @ cv
            for j in sorted(range(len(kept)), key=lambda j: -sims[j])[:3]:
                routed[kept[j].sid].append((ci, c))
        return routed

    def _relation_names(self) -> set:
        if not hasattr(self, "_rel_names"):
            self._rel_names = {to_lower_camel(p["label"]) for p in self.kb.docs["property"] if p["kind"] == "object"}
        return self._rel_names

    # ── Task 2: tagged values ────────────────────────────────────────────
    def _task2_evidence(self, profile: Profile, st: Stereotype,
                        constraints: Optional[List[Tuple[int, str]]] = None) -> EvidencePack:
        pack = EvidencePack()
        for ref in st.ontology_refs[:4]:
            doc = self.kb.class_by_uri.get(ref.uri or "")
            if doc:
                pack.add_class(doc)
        text = f"{split_camel(st.name)} {st.description}"
        for doc, _ in self.kb.search("property", text, k=6):
            pack.add_property(doc)
        for doc, _ in self.kb.search("class", f"{text} measurement unit", k=5, filters={"sources": ["UO"]}):
            pack.add_unit(doc)
        for doc, _ in self.kb.search("class", f"{text} quality", k=3, filters={"sources": ["PATO"]}):
            pack.add_unit(doc)
        facets = " ".join(self._facet_values(profile.analysis, self.domain.metaclass_focus[st.extends].facets))
        for doc, _ in self.kb.search_many("chunk", [(text, 1.0, None), (f"{text} {facets}", 0.6, None)],
                                          k=config.SOP_CHUNKS_PER_PROMPT - 1):
            pack.add_chunk(doc, words=80)
        for i, c in constraints or []:
            pack.add_context(i, c)
        return pack

    def _task2_one(self, profile: Profile, st: Stereotype, constraints: Optional[List[Tuple[int, str]]] = None):
        pack = self._task2_evidence(profile, st, constraints)
        others = [f"«{s.name}» ({s.extends})" for s in profile.kept() if s.sid != st.sid]
        enums = [f"{e.name} {{{', '.join(e.literals)}}}" for e in profile.enumerations]
        evidence = {p: pack.text(p) for p in "OPUSC"}
        prompt = tags_prompt(self.domain, self._digest(profile, st.extends), None,
                             st, others, enums, evidence, 4, 8, "")
        schema = tags_schema(pack.ids("O", "P", "U", "S", "C"), 4, 8)
        raw = self.client.chat_json(SYSTEM, prompt, schema, max_tokens=2600, task=f"task2 {st.name}")
        return raw, pack

    def _tag_from_raw(self, raw: Dict[str, Any], pack: EvidencePack, enums: Dict[str, Enumeration],
                      stereo_names: List[str]) -> Optional[TaggedValue]:
        """Store a tagged value exactly as Qwen produced it (no coercion or verification)."""
        name = to_lower_camel(str(raw.get("name", "")))
        if not raw.get("name"):
            return None
        typ = str(raw.get("type", "") or "String").strip()
        num = lambda v: float(v) if isinstance(v, (int, float)) else None
        evidence = pack.resolve(raw.get("evidence", []))
        value_source = raw.get("value_source", "default")
        if value_source not in ("SOP", "ontology", "context", "default"):
            value_source = "default"
        return TaggedValue(
            name=name, type=typ, multiplicity=str(raw.get("multiplicity", "1") or "1"),
            unit=str(raw.get("unit", "") or "").strip(), min=num(raw.get("min")), max=num(raw.get("max")),
            example=str(raw.get("example", "") or "").strip(), description=str(raw.get("description", "")).strip(),
            value_source=value_source, evidence=evidence, verified=bool(evidence), origin="task2")

    def _associations(self, profile: Profile, force: bool) -> int:
        """Global step: association-typed tags between stereotypes (one call over the whole profile)."""
        kept = profile.kept()
        if len(kept) < 2:
            return 0
        names = [s.name for s in kept]
        by_name = {s.name: s for s in kept}
        lines = []
        for m in METACLASSES:
            group = [s for s in kept if s.extends == m]
            if group:
                lines.append(f"{m}: " + "; ".join(f"«{s.name}» — "
                                                  f"{s.description[:90]}" for s in group))
        n_min, n_max = max(4, len(kept) // 2), min(40, len(kept) * 2)
        raw = self.client.chat_json(
            SYSTEM, associations_prompt(self.domain, self._digest(profile), "\n".join(lines), n_min, n_max),
            associations_schema(names, [], n_min, n_max), max_tokens=90 * n_max + 300, task="task2 associations")
        added = 0
        for a in raw.get("associations", []) or []:
            src, tgt = by_name.get(a.get("source")), by_name.get(a.get("target"))
            if not src or not tgt or src.sid == tgt.sid:
                continue
            tags = profile.tagged_values.setdefault(src.sid, [])
            if any(t.type == tgt.name for t in tags):
                continue  # already linked
            name = to_lower_camel(str(a.get("name") or tgt.name))
            if any(t.name == name for t in tags):
                name = to_lower_camel(tgt.name)
                if any(t.name == name for t in tags):
                    continue
            evidence = []
            tags.append(TaggedValue(
                name=name, type=tgt.name, multiplicity=normalize_multiplicity(str(a.get("multiplicity", "1"))),
                example=tgt.name, description=str(a.get("rationale", "")).strip(),
                value_source="default", evidence=evidence,
                verified=True, origin="task2"))
            added += 1
        return added

    def run_task2(self, profile: Profile, sids: Optional[List[str]] = None, force: bool = False,
                  progress: Progress = None) -> Profile:
        targets = [s for s in profile.kept() if (sids is None or s.sid in sids)
                   and (force or not profile.tagged_values.get(s.sid))]
        routed = self._route_constraints(profile)
        jobs = [(st.name, (lambda st=st: self._task2_one(profile, st, routed.get(st.sid))))
                for st in targets]
        results, errors = self._run_parallel(jobs, progress, "Tagged values", (0.02, 0.88))

        stereo_names = [s.name for s in profile.kept()]
        enums: Dict[str, Enumeration] = {e.name: e for e in profile.enumerations}
        alias: Dict[str, str] = {}
        for key, (raw, pack) in results.items():
            for e in raw.get("enumerations", []) or []:
                name = to_upper_camel(str(e.get("name", "")))
                if name in stereo_names or name in PRIMITIVE_TYPES or name in METACLASSES or name == "Unnamed":
                    continue
                literals = list(dict.fromkeys(to_enum_literal(str(l)) for l in e.get("literals", []) if str(l).strip()))
                if len(literals) < 2:
                    continue
                same = next((e for e in enums.values() if set(e.literals) == set(literals)), None)
                if same and same.name != name:
                    alias[name] = same.name  # identical value set → reuse the existing enumeration
                    continue
                if name in enums:
                    merged = list(dict.fromkeys(enums[name].literals + literals))[:15]
                    enums[name].literals = merged
                else:
                    enums[name] = Enumeration(name=name, literals=literals[:15],
                                              description=str(e.get("description", "")).strip(),
                                              evidence=pack.resolve(e.get("evidence", [])))
        for st in targets:
            if st.name not in results:
                continue
            raw, pack = results[st.name]
            tags: List[TaggedValue] = []
            seen = set()
            for item in raw.get("tagged_values", []) or []:
                if str(item.get("type", "")) in alias:
                    item = {**item, "type": alias[str(item.get("type", ""))]}
                tag = self._tag_from_raw(item, pack, enums, stereo_names)
                if tag is None or tag.name in seen:
                    continue
                seen.add(tag.name)
                tags.append(tag)
            profile.tagged_values[st.sid] = tags
        profile.enumerations = list(enums.values())
        if targets:
            if progress:
                progress("Linking stereotypes", 0.92)
            try:
                n_assoc = self._associations(profile, force)
                self._log(profile, "task2", f"{n_assoc} associations")
            except LLMError as exc:
                errors["associations"] = str(exc)
        cleanup_enumerations(profile)
        for key, err in errors.items():
            self._log(profile, "task2", f"«{key}» failed: {err}", level="error")
        self._log(profile, "task2", f"tagged values for {len(results)} stereotypes", usage=self.client.usage_summary())
        profile.updated = now()
        return profile

    # ── Task 3: OCL invariants ───────────────────────────────────────────
    def _reachable(self, profile: Profile, st: Stereotype, depth: int = 2) -> List[Stereotype]:
        by_name = {s.name: s for s in profile.kept()}
        seen, frontier, out = {st.name}, [st], []
        for _ in range(depth):
            nxt = []
            for s in frontier:
                for t in profile.tagged_values.get(s.sid, []):
                    target = by_name.get(t.type)
                    if target and target.name not in seen:
                        seen.add(target.name)
                        out.append(target)
                        nxt.append(target)
            frontier = nxt
        return out[:8]

    @staticmethod
    def _tag_line(t: TaggedValue, stereo_names: List[str]) -> str:
        extra = []
        if t.unit:
            extra.append(t.unit)
        if t.min is not None or t.max is not None:
            extra.append(f"range {'' if t.min is None else t.min}..{'' if t.max is None else t.max}")
        if t.type in stereo_names:
            extra.append(f"association → «{t.type}»")
        return f"{t.name} : {t.type} [{t.multiplicity}]" + (f" ({'; '.join(extra)})" if extra else "")

    def vocabulary(self, profile: Profile, st: Stereotype, extra: Optional[Dict[str, List[dict]]] = None) -> str:
        names = [s.name for s in profile.kept()]
        own = profile.tagged_values.get(st.sid, [])
        lines = [f"CONTEXT STEREOTYPE «{st.name}» extends {st.extends} — {st.description}",
                 f"  tagged values of «{st.name}»:"]
        lines += [f"    - {self._tag_line(t, names)}" for t in own] or ["    - (none yet)"]
        for t in (extra or {}).get(st.name, []):
            lines.append(f"    - {t['name']} : {t['type']} [{t['multiplicity']}] (declared by you)")
        reach = self._reachable(profile, st)
        if reach:
            lines.append("REACHABLE STEREOTYPES (navigate through the association tags):")
            for r in reach:
                tags = "; ".join(self._tag_line(t, names) for t in profile.tagged_values.get(r.sid, [])) or "(no tags)"
                lines.append(f"  «{r.name}» ({r.extends}): {tags}")
        used = {t.type for s in [st] + reach for t in profile.tagged_values.get(s.sid, [])}
        enums = [e for e in profile.enumerations if e.name in used] or profile.enumerations[:6]
        if enums:
            lines.append("ENUMERATIONS: " + "; ".join(f"{e.name} = {{{', '.join(e.literals)}}}" for e in enums))
        lines.append("ALL STEREOTYPES (usable in oclIsKindOf): " + ", ".join(names))
        return "\n".join(lines) + "\n"

    def _task3_evidence(self, profile: Profile, st: Stereotype,
                        constraints: Optional[List[Tuple[int, str]]] = None) -> EvidencePack:
        pack = EvidencePack()
        tags = " ".join(split_camel(t.name) for t in profile.tagged_values.get(st.sid, []))
        text = f"{split_camel(st.name)} {st.description}"
        facets = " ".join(self._facet_values(profile.analysis, self.domain.metaclass_focus[st.extends].facets))
        queries = [(f"{text} {tags}", 1.0, None), (f"{text} {facets}", 0.6, None)]
        for doc, _ in self.kb.search_many("rule", queries, k=config.RULES_PER_PROMPT):
            pack.add_rule(doc)
        for doc, _ in self.kb.search_many("chunk", queries, k=2):
            pack.add_chunk(doc, words=70)
        for ref in st.ontology_refs[:3]:
            doc = self.kb.class_by_uri.get(ref.uri or "")
            for restr in (doc or {}).get("restrictions", [])[:3]:
                if restr["filler_label"] not in ("…", "Thing"):
                    pack.add_axiom(doc["label"], doc["uri"], restr)
        for i, c in constraints or []:
            pack.add_context(i, c)
        return pack

    def _task3_one(self, profile: Profile, st: Stereotype, constraints: Optional[List[Tuple[int, str]]] = None):
        pack = self._task3_evidence(profile, st, constraints)
        stereo_names = [s.name for s in profile.kept()]
        prompt = ocl_prompt(self.domain, self._digest(profile, st.extends), st, self.vocabulary(profile, st),
                            {p: pack.text(p) for p in "RSAC"}, [], 2, 4)
        schema = ocl_schema(pack.ids("R", "S", "A", "C"), stereo_names, 2, 4)
        raw = self.client.chat_json(SYSTEM, prompt, schema, max_tokens=2400, task=f"task3 {st.name}")
        produced = []
        for item in raw.get("invariants", []) or []:
            new_tags = [(nt.get("stereotype"), {
                "name": to_lower_camel(str(nt.get("name", ""))), "type": str(nt.get("type", "") or "String"),
                "multiplicity": str(nt.get("multiplicity", "1") or "1"), "unit": str(nt.get("unit", "") or "").strip()})
                for nt in item.get("new_tags", []) or [] if nt.get("stereotype") in stereo_names]
            requirement = _strip_citations(str(item.get("requirement", "")))
            produced.append((Invariant(
                iid="", name=to_upper_camel(str(item.get("name") or "Rule")), context=st.name,
                context_sid=st.sid, body=str(item.get("ocl", "")).strip(),
                reading=_strip_citations(str(item.get("reading", ""))),
                requirement=requirement, evidence=pack.resolve(item.get("evidence", [])),
                origin="llm"), new_tags))
        return produced

    def run_task3(self, profile: Profile, sids: Optional[List[str]] = None, force: bool = False,
                  progress: Progress = None) -> Profile:
        targets = [s for s in profile.kept() if (sids is None or s.sid in sids)
                   and (force or not any(i.context_sid == s.sid for i in profile.invariants))]
        target_sids = {s.sid for s in targets}
        profile.invariants = [i for i in profile.invariants if i.context_sid not in target_sids]
        routed = self._route_constraints(profile)
        jobs = [(st.name, (lambda st=st: self._task3_one(profile, st, routed.get(st.sid))))
                for st in targets]
        results, errors = self._run_parallel(jobs, progress, "OCL invariants", (0.02, 0.92))

        by_name = {s.name: s for s in profile.kept()}
        for st in targets:
            for inv, new_tags in results.get(st.name, []):
                profile.invariants.append(inv)
                for target, tag in new_tags:
                    tsid = by_name[target].sid
                    existing = profile.tagged_values.setdefault(tsid, [])
                    if any(t.name == tag["name"] for t in existing):
                        continue
                    existing.append(TaggedValue(
                        name=tag["name"], type=tag["type"], multiplicity=tag["multiplicity"], unit=tag["unit"],
                        description=f"Required by invariant {inv.name}", value_source="default",
                        evidence=inv.evidence, verified=bool(inv.evidence), origin="task3",
                        notes=[f"introduced by OCL invariant {inv.name}"]))

        # unique names / ids, drop duplicate bodies per context
        seen_bodies, names, kept = set(), set(), []
        for inv in profile.invariants:
            key = (inv.context_sid, re.sub(r"\s+", "", inv.body))
            if key in seen_bodies:
                continue
            seen_bodies.add(key)
            base, n = inv.name or "Rule", 2
            while inv.name in names:
                inv.name, n = f"{base}{n}", n + 1
            names.add(inv.name)
            kept.append(inv)
        order = {s.sid: i for i, s in enumerate(profile.stereotypes)}
        kept.sort(key=lambda i: order.get(i.context_sid, 999))
        for n, inv in enumerate(kept, start=1):
            inv.iid = f"INV-{n:02d}"
        profile.invariants = kept
        for inv in profile.invariants:
            if inv.origin == "llm" and inv.grounding == 0.0:
                text = f"{inv.requirement} {inv.reading}"
                inv.grounding = round(max(
                    self.kb.similarity(text, "rule", [e.id for e in inv.evidence if e.kind == "rule"]),
                    self.kb.similarity(text, "chunk", [e.id for e in inv.evidence if e.kind == "chunk"]),
                ), 3)
        for key, err in errors.items():
            self._log(profile, "task3", f"«{key}» failed: {err}", level="error")
        self._log(profile, "task3", f"{len(profile.invariants)} invariants", usage=self.client.usage_summary())
        profile.updated = now()
        return profile
